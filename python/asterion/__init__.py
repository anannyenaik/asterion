    for _dll_dir in (
        Path(sys.base_prefix),
        Path(sys.executable).resolve().parent,
        Path.home() / "msys64" / "ucrt64" / "bin",
        Path("C:/msys64/ucrt64/bin"),
    ):
        if _dll_dir.exists():
            os.add_dll_directory(str(_dll_dir))

